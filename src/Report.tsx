import { useEffect, useState } from 'react'
import { offboard, prioritized, reasons, severity, WEIGHTS } from './engine/risk.ts'
import { derive, today, useProject } from './projectData.ts'
import { saveProject, type Attestation, type Project } from './store.ts'
import { fmtDate, Link, NotFound, plural, toast } from './ui.tsx'
import { grade, HealthRing, Trend } from './viz.tsx'

export default function Report({ id, kind }: { id: string; kind: string }) {
  const { loading, project: p } = useProject(id)
  useEffect(() => { if (p) document.title = `${kind === 'attest' ? 'Attestation' : 'Report'} · ${p.name}` }, [p?.name, kind])
  if (loading) return <div className="boot"><span className="spinner" /> Loading</div>
  if (!p) return <NotFound />
  return (
    <div className="print-page">
      <div className="print-bar no-print">
        <Link href={`/app/p/${p.id}/actions`} className="btn ghost sm">&larr; Back</Link>
        <button type="button" className="btn primary sm" onClick={() => print()}>Print or save as PDF</button>
      </div>
      {kind === 'attest' ? <Attest p={p} /> : <Main p={p} />}
    </div>
  )
}

function Main({ p }: { p: Project }) {
  const person = new URLSearchParams(location.search).get('person')
  const d = derive(p)
  const g = grade(d.sum.health)
  const top = prioritized(d.eff, d.ctx).slice(0, 12)
  const snaps = [...p.snapshots].sort((a, b) => a.at.localeCompare(b.at))
  const plans = Object.entries(p.plans).map(([who, plan]) => {
    const raw = derive({ ...p, fixed: {} })
    const steps = offboard(who, raw.eff, p.access, raw.ctx, p.tags[who])
    return { who, plan, steps, done: steps.filter(s => plan.done[s.finding.id]).length }
  }).filter(x => !person || x.who === person)

  if (person) {
    const raw = derive({ ...p, fixed: {} })
    const steps = offboard(person, raw.eff, p.access, raw.ctx, p.tags[person])
    const done = p.plans[person]?.done ?? {}
    return (
      <article className="report">
        <header className="report-head"><div><div className="eyebrow">Offboarding checklist</div><h1>{person}</h1><p className="muted">{p.name} · prepared {fmtDate(Date.now())} · {steps.filter(s => done[s.finding.id]).length} of {steps.length} rotated</p></div></header>
        <table className="table report-table">
          <thead><tr><th>#</th><th>Done</th><th>Item</th><th>Owner</th><th>Also rotate</th><th>Notes</th></tr></thead>
          <tbody>{steps.map((s, i) => (
            <tr key={s.finding.id}><td>{i + 1}</td><td>{done[s.finding.id] ? `✓ ${fmtDate(done[s.finding.id])}` : '☐'}</td><td><strong>{s.finding.title}</strong><div className="small muted">{s.finding.domain}</div></td><td>{s.owner}</td><td className="small">{s.also.map(a => a.title).join(', ') || '—'}</td><td className="small">{s.why.slice(1).join('; ')}{s.finding.sso ? '; SSO candidate' : ''}</td></tr>
          ))}</tbody>
        </table>
        <footer className="report-foot">Generated by Vault Health from derived findings only. No passwords were stored.</footer>
      </article>
    )
  }

  return (
    <article className="report">
      <header className="report-head">
        <div>
          <div className="eyebrow">Credential hygiene report</div>
          <h1>{p.name}</h1>
          <p className="muted">Prepared {fmtDate(Date.now())} · {plural(d.sum.n, 'item')} across {plural(new Set(d.eff.map(f => f.vault)).size, 'vault')}{p.sampleId ? ' · synthetic sample data' : ''}</p>
        </div>
        <HealthRing sum={d.sum} size={150} />
      </header>
      <section>
        <h2>Summary</h2>
        <p>Overall health is <b>{d.sum.health}/100 ({g.label.toLowerCase()})</b>. {d.sum.breached} item{d.sum.breached === 1 ? '' : 's'} use a password found in public breaches, {d.sum.reused} share a password with another item and {d.sum.near} use a close variant of another password. {d.sum.old} passwords have not changed in over a year; {d.sum.missing2fa} sites support two-factor authentication without a saved TOTP code. {Object.keys(p.fixed).length ? `${plural(Object.keys(p.fixed).length, 'item')} have been rotated since the last import.` : ''}</p>
        <div className="report-stats">
          {([['Critical', d.sum.bySeverity.critical], ['High', d.sum.bySeverity.high], ['Medium', d.sum.bySeverity.medium], ['Low', d.sum.bySeverity.low], ['Breached', d.sum.breached], ['Reused', d.sum.reused], ['Old', d.sum.old], ['Shared', d.sum.shared]] as const).map(([l, n]) => <div key={l}><span>{l}</span><strong>{n}</strong></div>)}
        </div>
      </section>
      {snaps.length > 1 && <section><h2>Trend</h2><Trend points={snaps.map(s => ({ label: s.label, v: s.summary.health }))} /></section>}
      <section>
        <h2>Highest-risk items</h2>
        <table className="table report-table">
          <thead><tr><th>#</th><th>Item</th><th>Vault</th><th>Risk</th><th>Why</th></tr></thead>
          <tbody>{top.map(({ f, r }, i) => <tr key={f.id}><td>{i + 1}</td><td>{f.title}</td><td>{f.vault}</td><td>{r} ({severity(r)})</td><td className="small">{reasons(f, d.ctx).map(x => x.text).join('; ')}</td></tr>)}</tbody>
        </table>
      </section>
      {plans.length > 0 && (
        <section>
          <h2>Offboarding</h2>
          <table className="table report-table">
            <thead><tr><th>Person</th><th>Started</th><th>Rotated</th><th>Remaining</th></tr></thead>
            <tbody>{plans.map(x => <tr key={x.who}><td>{x.who}</td><td>{fmtDate(x.plan.created)}</td><td>{x.done} of {x.steps.length}</td><td className="small">{x.steps.filter(s => !x.plan.done[s.finding.id]).slice(0, 5).map(s => s.finding.title).join(', ') || 'None'}</td></tr>)}</tbody>
          </table>
        </section>
      )}
      <section className="small">
        <h2>Method</h2>
        <p>Per-item risk (0–100) adds: breached {WEIGHTS.breached}; reused {WEIGHTS.reusedBase} (+{WEIGHTS.reusedPerExtra} per extra item, max {WEIGHTS.reusedMax}); near-reuse {WEIGHTS.nearReuse}; strength 0–3: {WEIGHTS.strength.slice(0, 4).join('/')}; older than one year {WEIGHTS.olderThan1y}, two years {WEIGHTS.olderThan2y}; 2FA available but not set {WEIGHTS.missing2fa}; shared vault {WEIGHTS.sharedVault}. Health = 100 − ½ × mean risk − ½ × % of items rated high or critical. Breach status from Have I Been Pwned Pwned Passwords via k-anonymity; 2FA support from 2fa.directory.</p>
        {p.attest && <p>Policy attestation signed by {p.attest.signer} ({p.attest.role}) on {fmtDate(p.attest.date)}.</p>}
      </section>
      <footer className="report-foot">Generated by Vault Health from derived findings only. No passwords or usernames were stored or transmitted.</footer>
    </article>
  )
}

const STATEMENTS: [string, string][] = [
  ['rotate', 'Shared credentials a departing employee or contractor could access are rotated within 2 business days of their last day.'],
  ['inventory', 'Shared credentials are kept in a company password manager, not in documents, chat or email.'],
  ['review', 'Credential hygiene (breached, reused and stale passwords) is reviewed on the schedule below, and the results are kept.'],
  ['mfa', 'Two-factor authentication is enabled on every shared account whose service supports it.'],
  ['sso', 'Business applications that support single sign-on are moved behind SSO where the plan allows.'],
  ['unique', 'Every account uses a unique, generated password.'],
]

function Attest({ p }: { p: Project }) {
  const d = derive(p)
  const [a, setA] = useState<Attestation>(() => p.attest ?? { org: p.sampleId ? p.name : '', signer: '', role: '', date: today(), reviewEvery: 'Quarterly', statements: Object.fromEntries(STATEMENTS.map(([k]) => [k, true])) })
  const set = (patch: Partial<Attestation>) => setA(x => ({ ...x, ...patch }))
  const plans = Object.entries(p.plans)
  return (
    <article className="report attest">
      <header className="report-head"><div><div className="eyebrow">Policy attestation</div><h1>Shared credential management</h1><p className="muted">{a.org || 'Your organization'} · {fmtDate(a.date)}</p></div></header>
      <form className="attest-form no-print" onSubmit={e => { e.preventDefault(); void saveProject({ ...p, attest: a }).then(() => toast('Attestation saved', { tone: 'ok' })) }}>
        <label className="field"><span>Organization</span><input value={a.org} onChange={e => set({ org: e.target.value })} required /></label>
        <label className="field"><span>Signed by</span><input value={a.signer} onChange={e => set({ signer: e.target.value })} required /></label>
        <label className="field"><span>Role</span><input value={a.role} onChange={e => set({ role: e.target.value })} placeholder="IT administrator" required /></label>
        <label className="field"><span>Date</span><input type="date" value={a.date} onChange={e => set({ date: e.target.value })} required /></label>
        <label className="field"><span>Review frequency</span><select value={a.reviewEvery} onChange={e => set({ reviewEvery: e.target.value })}>{['Monthly', 'Quarterly', 'Twice a year', 'Annually'].map(x => <option key={x}>{x}</option>)}</select></label>
        <button className="btn primary">Save attestation</button>
      </form>
      <section>
        <p>On behalf of <b>{a.org || '__________'}</b>, I attest that the following controls are in place for shared credentials:</p>
        <ol className="statements">{STATEMENTS.map(([k, t]) => (
          <li key={k}><label className="check"><input type="checkbox" className="no-print" checked={!!a.statements[k]} onChange={() => set({ statements: { ...a.statements, [k]: !a.statements[k] } })} /><span className={a.statements[k] ? '' : 'struck'}>{k === 'review' ? t.replace('the schedule below', a.reviewEvery.toLowerCase()) : t}</span></label></li>
        ))}</ol>
        <h3>Evidence as of {fmtDate(Date.now())}</h3>
        <ul>
          <li>Vault health score {d.sum.health}/100 across {plural(d.sum.n, 'item')}; {d.sum.breached} breached, {d.sum.reused} reused.</li>
          <li>{plural(p.snapshots.length, 'review snapshot')} on record{p.snapshots.length ? `, the first on ${fmtDate([...p.snapshots].sort((x, y) => x.at.localeCompare(y.at))[0].at)}` : ''}.</li>
          {plans.length ? plans.map(([who, plan]) => <li key={who}>Offboarding of {who}: started {fmtDate(plan.created)}, {Object.keys(plan.done).length} credentials rotated.</li>) : <li>No offboarding plans recorded.</li>}
        </ul>
        <div className="sign">
          <div><span>{a.signer || ' '}</span><small>Name</small></div>
          <div><span>{a.role || ' '}</span><small>Role</small></div>
          <div><span>&nbsp;</span><small>Signature</small></div>
          <div><span>{fmtDate(a.date)}</span><small>Date</small></div>
        </div>
      </section>
      <footer className="report-foot">Prepared with Vault Health. This attestation is the signer’s statement; the tool records only derived findings.</footer>
    </article>
  )
}
